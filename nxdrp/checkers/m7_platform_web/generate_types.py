"""Generate TS and local schemas from authoritative Python dataclasses.

The baseline three schema documents are also exported without changing shared files.
Dataclass-derived definitions fill gaps in the current baseline (bbox, evidence,
path_points, CheckRun). This generator needs only the standard library.
"""
from __future__ import annotations
import dataclasses
import json
from pathlib import Path
import sys
import types
import typing as t

MODULE = Path(__file__).resolve().parent
sys.path.insert(0, str(MODULE.parents[2]))
from nxdrp.contracts import core
from nxdrp.pipeline import CheckRun, CheckerResult
from nxdrp.checkers.m7_platform_web.backend._service import Task, DisplayMesh


def generate():
    classes = [core.BBox, core.Part, core.Face, core.Edge, core.Occurrence, core.ModelBundle,
               core.Rule, core.RuleBook, core.Evidence, core.Suggestion, core.Detector,
               core.Finding, CheckerResult, CheckRun, Task, DisplayMesh]

    def ts(hint):
        origin, args = t.get_origin(hint), t.get_args(hint)
        if hint is t.Any: return "unknown"
        if hint is type(None): return "null"
        if hint in (str, int, float, bool): return {str: "string", int: "number", float: "number", bool: "boolean"}[hint]
        if dataclasses.is_dataclass(hint): return hint.__name__
        if origin in (t.Union, types.UnionType): return " | ".join(ts(a) for a in args)
        if origin is dict or hint is dict: return "Record<string, " + (ts(args[1]) if args else "unknown") + ">"
        if origin is list: return "(" + ts(args[0]) + ")[]"
        if origin is tuple:
            return "(" + ts(args[0]) + ")[]" if Ellipsis in args else "[" + ", ".join(ts(a) for a in args) + "]"
        return "unknown"

    def schema(hint):
        origin, args = t.get_origin(hint), t.get_args(hint)
        if hint in (str, int, float, bool): return {"type": {str:"string", int:"integer", float:"number", bool:"boolean"}[hint]}
        if hint is type(None): return {"type": "null"}
        if dataclasses.is_dataclass(hint): return {"$ref": "#/$defs/" + hint.__name__}
        if origin in (t.Union, types.UnionType): return {"anyOf": [schema(a) for a in args]}
        if origin in (tuple, list):
            if origin is tuple and Ellipsis not in args:
                return {"type": "array", "prefixItems": [schema(a) for a in args], "minItems": len(args), "maxItems": len(args)}
            return {"type": "array", "items": schema(args[0])}
        if origin is dict or hint is dict: return {"type": "object", "additionalProperties": schema(args[1]) if args else {}}
        return {}

    lines = ["// Generated by generate_types.py. Do not edit by hand."]
    definitions = {}
    for cls in classes:
        hints = t.get_type_hints(cls)
        fields = {f.name: hints[f.name] for f in dataclasses.fields(cls)}
        lines.append("export interface " + cls.__name__ + " {\n" + "\n".join(f"  {name}: {ts(hint)}" for name, hint in fields.items()) + "\n}")
        definitions[cls.__name__] = {"type": "object", "properties": {name: schema(h) for name, h in fields.items()}, "required": list(fields)}
    output = MODULE / "frontend/src/generated"
    output.mkdir(parents=True, exist_ok=True)
    (output / "contracts.ts").write_text("\n\n".join(lines) + "\n", encoding="utf-8")
    directory = MODULE / "contracts"
    directory.mkdir(exist_ok=True)
    for name, document in core.schema_documents().items():
        (directory / name).write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    document = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": definitions}
    (directory / "web-contracts.schema.json").write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    generate()
